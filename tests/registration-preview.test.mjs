import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import test from 'node:test';
import assert from 'node:assert/strict';
const setup=readFileSync(new URL('../public/admin/setup.js',import.meta.url),'utf8');
const start=setup.indexOf('  const RegistrationFormControl');
const end=setup.indexOf('  const RegistrationRosterControl',start);
const widgets={};
const context=vm.createContext({URL,crypto:{randomUUID:()=> 'test-id'},window:{createClass:component=>component,h:(tag,props,...children)=>({tag,props,children}),CMS:{registerWidget:(name,control)=>widgets[name]=control}},CMS:{registerWidget:(name,control)=>widgets[name]=control}});
vm.runInContext(setup.slice(start,end),context);
const nodes=tree=>tree? [tree,...(tree.children||[]).filter(value=>value&&typeof value==='object').flatMap(nodes)]:[];
test('generated form link is hidden before publish and displayed afterward',()=>{
  const control=widgets['registration-form'];
  assert.equal(control.render.call({props:{value:''}}),null);
  assert.equal(control.render.call({props:{value:'javascript:alert(1)'}}),null);
  const tree=control.render.call({props:{value:'https://docs.google.com/forms/d/e/test/viewform'}});
  const all=nodes(tree);
  assert.equal(all.find(node=>node.tag==='a').props.target,'_blank');
  assert.ok(!all.some(node=>node.tag==='input'||node.tag==='iframe'));
});
test('question editor and preview share the same value and expose editable fields',()=>{
  const control=widgets['registration-builder'];let value=null;
  const props={value,onChange:next=>{value=next}};
  let instance=Object.assign(Object.create(control),{props});let all=nodes(instance.render());
  const title=all.find(node=>node.tag==='input'&&node.props['aria-label']==='1번 질문 제목');
  assert.ok(title);title.props.onChange({target:{value:'참가자 성명'}});
  instance=Object.assign(Object.create(control),{props:{...props,value}});all=nodes(instance.render());
  assert.ok(all.some(node=>node.tag==='div'&&node.children.includes('참가자 성명 *')));
  assert.ok(all.some(node=>node.tag==='button'&&node.children.includes('질문 추가')));
});
